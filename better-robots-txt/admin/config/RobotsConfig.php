    /**
     * Generate robots.txt rules for granular bot control
     * Supports 3-state logic: global / allow / disallow
     *
     * @param array $customBots Associative array of bot_id => state ('global'|'allow'|'disallow')
     * @param string $category Bot category to get default list from
     * @param string $comment Optional comment to add before rules
     * @return string Robots.txt formatted string
     */
    public static function generateGranularBotRules($customBots, $category, $comment = '')
    {
        $allBots = self::getMasterPlanBotsByCategory($category);

        if (empty($allBots)) {
            return '';
        }

        $output = '';
        if ($comment) {
            $output .= "# {$comment}\n";
        }

        foreach ($customBots as $botId => $state) {
            // Skip if state is 'global' (uses User-agent: * rules)
            if ($state === 'global') {
                continue;
            }

            // Get User-Agent string
            $userAgent = $allBots[$botId] ?? null;
            if (!$userAgent) {
                continue;
            }

            // Generate rule based on state
            if ($state === 'allow') {
                $output .= "User-agent: {$userAgent}\nAllow: /\n\n";
            } elseif ($state === 'disallow') {
                $output .= "User-agent: {$userAgent}\nDisallow: /\n\n";
            }
        }

        return $output;
    }
