    /**
     * Generate global base rules for WordPress
     * These rules apply to all user agents and are always included
     *
     * @return string Robots.txt formatted base rules
     */
    public static function generateBaseRules($rules = [])
    {
        $output = "# Global base rules\n";
        $output .= "User-agent: *\n";

        // Add Allow rules
        foreach (self::BASE_ALLOW_PATHS as $path) {
            $output .= "Allow: {$path}\n";
        }

        // --- Granular Disallow Rules ---

        // WordPress Admin (Default: true)
        if ($rules['block_wp_admin'] ?? true) {
            $output .= "Disallow: /wp-admin/\n";
        }

        // WordPress Includes (Default: true)
        if ($rules['block_wp_includes'] ?? true) {
            $output .= "Disallow: /wp-includes/\n";
        }

        // Readme & License (Default: true)
        if ($rules['block_readme'] ?? true) {
            $output .= "Disallow: /readme.html\n";
            $output .= "Disallow: /license.txt\n";
        }

        // XML-RPC (Default: true)
        if ($rules['block_xmlrpc'] ?? true) {
            $output .= "Disallow: /xmlrpc.php\n";
        }

        // Login & Register (Default: true)
        if ($rules['block_login'] ?? true) {
            $output .= "Disallow: /wp-login.php\n";
            $output .= "Disallow: /wp-register.php\n";
        }

        // Disclaimer (Default: true)
        if ($rules['block_disclaimer'] ?? true) {
            $output .= "Disallow: */disclaimer/*\n";
        }

        // Attachments & Filtering (Default: true)
        if ($rules['block_attachments'] ?? true) {
            $output .= "Disallow: *?attachment_id=\n";
            $output .= "Disallow: /*?filtering=\n";
        }

        $output .= "\n";

        return $output;
    }

