    /**
     * Get signature line (or empty if removed)
     *
     * @param bool $removeSignature Whether to remove signature
     * @param string $customText Optional custom footer comment
     * @return string Signature block or empty string
     */
    public static function getSignature($removeSignature = false, $customText = '')
    {
        if ($removeSignature) {
            return '';
        }

        $formattedCustomText = self::formatFooterComment($customText);
        $output = "\n";

        if ($formattedCustomText !== '') {
            $output .= $formattedCustomText . "\n\n";
        }

        return $output;
    }

    /**
     * Format footer text as comment lines.
     *
     * @param string $text
     * @return string
     */
    private static function formatFooterComment($text)
    {
        if (!is_string($text) || trim($text) === '') {
            return '';
        }

        $lines = preg_split('/\r\n|\r|\n/', $text);
        $formatted = [];

        foreach ($lines as $line) {
            $line = trim($line);

            if ($line === '') {
                continue;
            }

            $line = preg_replace('/[^\x20-\x7E]/', '', $line);

            if ($line === '') {
                continue;
            }

            if (strpos($line, '#') !== 0) {
                $line = '# ' . $line;
            }

            $formatted[] = $line;
        }

        return implode("\n", $formatted);
    }

